"""Render the findings as a single browsable Markdown document.

The JSON records are the source of truth; this file exists so the dataset can
be read without a JSON viewer. Because the output is generated, it is checked
rather than edited: `--check` compares the rendered text against the file on
disk and fails if they differ, which keeps a stale catalog from being merged.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
CATALOG_PATH = REPO_ROOT / "docs" / "CATALOG.md"

SEVERITY_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3}


def load_findings(repo_root: Path) -> list[dict[str, Any]]:
    """Load every record, ordered by severity and then by id."""
    records = [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted((repo_root / "findings").rglob("*.json"))
    ]
    return sorted(records, key=lambda r: (SEVERITY_ORDER[r["severity"]], r["id"]))


def _fence(code: str, language: str) -> str:
    return f"```{language}\n{code}\n```"


def _snippet_language(record: dict[str, Any]) -> str:
    return "python" if record["language"] == "python" else "typescript"


def render_summary(records: list[dict[str, Any]]) -> str:
    """Render the index table that opens the catalog."""
    lines = [
        "| ID | Severity | Category | Language | Finding |",
        "| --- | --- | --- | --- | --- |",
    ]
    for record in records:
        anchor = record["id"]
        lines.append(
            f"| [`{record['id']}`](#{anchor}) | {record['severity']} | {record['category']} "
            f"| {record['language']} | {record['title']} |"
        )
    return "\n".join(lines)


def render_record(record: dict[str, Any]) -> str:
    """Render one finding as a section."""
    lines = [
        f"### {record['id']}",
        "",
        f"**{record['title']}**",
        "",
        f"`{record['severity']}` · `{record['category']}` · "
        f"[`{record['snippet']}`](../{record['snippet']}) · "
        f"line{'s' if len(record['defect_lines']) > 1 else ''} "
        + ", ".join(str(n) for n in record["defect_lines"]),
        "",
        "**Mechanism**",
        "",
        record["explanation"],
        "",
        "**Trigger**",
        "",
        record["trigger"],
        "",
        f"- Observed: {record['observed']}",
        f"- Expected: {record['expected']}",
        "",
        "**Fix**",
        "",
        _fence(record["fix"], _snippet_language(record)),
        "",
        record["fix_rationale"],
    ]

    if record.get("distractors"):
        lines += ["", "**Correct as written**", ""]
        lines += [f"- {item}" for item in record["distractors"]]

    if record.get("references"):
        lines += ["", "**References**", ""]
        lines += [f"- <{url}>" for url in record["references"]]

    return "\n".join(lines)


def render_catalog(repo_root: Path = REPO_ROOT) -> str:
    """Render the whole catalog, ordered most severe first."""
    records = load_findings(repo_root)
    parts = [
        "# Catalog",
        "",
        "Generated by `tools/catalog.py`. Edit the JSON records under `findings/`, "
        "not this file.",
        "",
        f"{len(records)} findings, ordered by severity.",
        "",
        render_summary(records),
        "",
        "---",
        "",
    ]
    parts.append("\n\n---\n\n".join(render_record(record) for record in records))
    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the committed catalog differs from the rendered one.",
    )
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT)
    args = parser.parse_args(argv)

    rendered = render_catalog(args.repo_root)
    target = args.repo_root / "docs" / "CATALOG.md"

    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != rendered:
            print(
                f"{target.relative_to(args.repo_root)} is out of date; "
                "run `make catalog` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"{target.relative_to(args.repo_root)} is up to date")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(rendered, encoding="utf-8")
    print(f"wrote {target.relative_to(args.repo_root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
